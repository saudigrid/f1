import type { Metadata } from 'next';

import { PageHeader } from '@/components/site/PageHeader';
import { PIPELINE_CONFIG } from '@/lib/config/pipeline';
import { CATEGORY_LABELS } from '@/lib/types';

export const metadata: Metadata = {
  title: 'السياسة التحريرية',
  description: 'كيف نجمع الأخبار ونحرّرها وندقّقها قبل النشر، ومتى يتدخّل محرّر بشري.',
  alternates: { canonical: '/editorial-policy' },
};

export default function EditorialPolicyPage() {
  const reviewOnly = PIPELINE_CONFIG.alwaysReviewCategories
    .map((c) => CATEGORY_LABELS[c])
    .join(' و');

  return (
    <div className="mx-auto max-w-3xl px-4 py-12 sm:px-6">
      <PageHeader
        title="السياسة التحريرية"
        lead="نشرح هنا بالضبط كيف يصل الخبر إليك: من أين نأخذه، وكيف نتحقق منه، ومتى نمتنع عن نشره."
      />

      <div className="prose-ar">
        <h2>من أين تأتي الأخبار</h2>
        <p>
          نتابع خلاصات المصادر الرسمية والمتخصصة في رياضة الفورمولا 1، وعلى رأسها الاتحاد
          الدولي للسيارات (FIA) والمنافذ المتخصصة المعروفة. نرصد الحدث من عدة مصادر، ثم نعيد
          تحريره بصياغة عربية أصلية — لا نترجم مقالات المصادر حرفياً ولا نعيد نشرها.
        </p>

        <h2>كيف نتحقق قبل النشر</h2>
        <p>
          كل خبر يمرّ بمرحلة تدقيق تفحص الادعاءات الواقعية فيه واحداً واحداً: الأرقام، التواريخ،
          نسبة التصريحات لقائليها، وحالة العقود والقرارات الرسمية — وتقارنها بما ورد في المصادر
          التي بُني عليها الخبر. يُخصَّص للخبر بعدها تقييم دقة رقمي، ويُعرض على المحرّر مع
          الادعاءات التي لم تُؤكَّد.
        </p>
        {PIPELINE_CONFIG.requireHumanReview ? (
          <p>
            <strong>كل خبر يمرّ على محرّر بشري قبل النشر، بلا استثناء.</strong> لا يُنشر شيء
            على هذا الموقع اعتماداً على التقييم الآلي وحده. التقييم أداة تساعد المحرّر على
            ترتيب أولوياته والانتباه لما يحتاج تدقيقاً، لا بديل عن قراره.
          </p>
        ) : (
          <p>
            لا يُنشر خبر تلقائياً إلا إذا تجاوز تقييمه{' '}
            <strong className="tnum">{PIPELINE_CONFIG.autoPublishConfidence}</strong> من 100،
            وأكّده ما لا يقل عن{' '}
            <strong className="tnum">{PIPELINE_CONFIG.minCorroboratingSources}</strong> من
            المنافذ المستقلة، وكانت كل ادعاءاته مدعومة. ما دون ذلك يذهب إلى مراجعة بشرية قبل
            النشر.
          </p>
        )}

        <h2>ما لا يُنشر تلقائياً أبداً</h2>
        <ul>
          <li>أخبار {reviewOnly} — تصل للمراجعة البشرية مهما ارتفع تقييمها.</li>
          <li>أي خبر يحتوي ادعاءً واحداً غير مؤكد، مهما كان بقيته سليماً.</li>
          <li>الأخبار التي تتناقض فيها المصادر.</li>
          <li>التكهّنات وإشاعات سوق السائقين.</li>
        </ul>

        <h2>الشائعات والتقارير غير المؤكدة</h2>
        <p>
          حين ننشر تقريراً لم تؤكده جهة رسمية، نقول ذلك صراحة في متن الخبر وننسبه إلى ناقله.
          لا نقدّم الإشاعة بصيغة الخبر المؤكد.
        </p>

        <h2>الإسناد</h2>
        <p>
          كل خبر مستمد من مصادر خارجية يذكر تلك المصادر في أسفله مع روابطها المباشرة. نقتبس من
          المصدر جملة قصيرة واحدة على الأكثر، منسوبة لقائلها.
        </p>

        <h2>التصحيح</h2>
        <p>
          إذا وصلنا خطأ في خبر منشور، نصحّحه ونوضّح التصحيح في الخبر نفسه. للتبليغ عن خطأ استخدم
          صفحة الاتصال.
        </p>

        <h2>الاستقلالية</h2>
        <p>
          هذا موقع مستقل غير تابع لـ Formula 1 أو الاتحاد الدولي للسيارات أو أي فريق. المحتوى
          التحريري لا يتأثر بالمعلنين، والمواد الإعلانية مُعلَّمة بوضوح.
        </p>
      </div>
    </div>
  );
}
