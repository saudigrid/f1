/**
 * شكل سجلّ فهرس البحث — مشترك بين السكربت الذي يبنيه والمكوّن الذي يقرأه.
 *
 * الحروف المختصرة (`n` لا `name`) مقصودة: الفهرس يحمل 1146 سجلّاً ويُجلب في
 * متصفّح القارئ، فكل حرف زائد في كل مفتاح يتكرّر 1146 مرّة.
 */
export type SearchKind = 'driver' | 'team' | 'circuit' | 'era';

export interface SearchEntry {
  /** النوع — يحدّد الأيقونة والتصنيف في النتائج. */
  k: SearchKind;
  /** الاسم العربي. */
  n: string;
  /** الاسم اللاتيني. */
  e: string;
  /** الرابط. */
  h: string;
  /** سطر ثانٍ: الجنسية أو البلد أو المدى الزمني. */
  s?: string;
  /** صورة مصغّرة إن وُجدت. */
  i?: string;
  /** بطل عالم / فريق نشط — يُرفع في الترتيب. */
  p?: 1;
}
